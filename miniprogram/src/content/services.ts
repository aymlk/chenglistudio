/**
 * 婚礼服务业务数据，与价格表一一对应。
 * 三大类别：婚礼摄影 / 婚礼摄像 / 婚礼摄影摄像。
 *
 * 每个套餐的 `details` 包含：包含项、不包含项、适合场景、拍摄流程、交付周期。
 * 卡片只显示精简版（name + price + highlights + items），
 * 点开后用 ServiceDetailModal 展示完整说明。
 */

export type ServiceDetails = {
  /** 包含项目（详版） */
  includes: string[]
  /** 不包含项 */
  excludes: string[]
  /** 适合场景 */
  suitable: string[]
  /** 拍摄流程（按阶段列出） */
  workflow: string[]
  /** 交付周期 */
  delivery: string
}

export type ServicePackage = {
  id: string
  number: string
  name: string
  price: string
  /** 卡片顶部标签，例如「精修 40 张 / 当天预告 12 张」 */
  highlights: string[]
  /** 详细说明清单（精简版，显示在卡片本体） */
  items: string[]
  /** 完整说明（点开 modal 后展开） */
  details: ServiceDetails
}

